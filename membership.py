"""Phone/password membership primitives (standard library, server-side only).

Render free instances have ephemeral local storage: do NOT use a local SQLite file for
production memberships without a persistent disk or external database.
"""
import hashlib
import hmac
import re
import secrets
import sqlite3
import time

ITERATIONS = 600_000
SESSION_SECONDS = 12 * 3600


def normalize_phone(phone):
    value = re.sub(r"[\s()\-]", "", str(phone))
    if re.fullmatch(r"(?:\+90|0090|90|0)?5[0-9]{9}", value):
        value = "+90" + value[-10:]
    if not re.fullmatch(r"\+?[0-9]{10,15}", value):
        raise ValueError("Geçerli telefon numarası girin")
    return value


def password_hash(password, salt=None):
    if not isinstance(password, str) or not 12 <= len(password) <= 256:
        raise ValueError("Şifre 12–256 karakter olmalı")
    salt = salt or secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, ITERATIONS)
    return f"pbkdf2_sha256${ITERATIONS}${salt.hex()}${digest.hex()}"


def verify_password(password, stored):
    try:
        algo, iterations, salt, expected = stored.split("$")
        if algo != "pbkdf2_sha256" or not (100_000 <= int(iterations) <= 2_000_000):
            return False
        actual = hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), int(iterations))
        return hmac.compare_digest(actual, bytes.fromhex(expected))
    except (ValueError, AttributeError, TypeError):
        return False


class PostgresConnection:
    def __init__(self, url):
        import certifi
        import psycopg
        from psycopg.rows import dict_row

        self.connection = psycopg.connect(url, row_factory=dict_row, connect_timeout=8,
                                          sslmode="verify-full", sslrootcert=certifi.where())

    def execute(self, query, parameters=()):
        return self.connection.execute(query.replace("?", "%s"), parameters)

    def commit(self):
        self.connection.commit()

    def close(self):
        self.connection.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, traceback):
        if exc_type:
            self.connection.rollback()
        else:
            self.commit()


def connect(path):
    if isinstance(path, str) and path.startswith(("postgresql://", "postgres://")):
        return PostgresConnection(path)

    db = sqlite3.connect(path, timeout=10)
    db.row_factory = sqlite3.Row
    db.execute("PRAGMA foreign_keys=ON")
    db.execute("PRAGMA busy_timeout=10000")
    return db


def initialize(db):
    schema = """
    CREATE TABLE IF NOT EXISTS members (
        id INTEGER PRIMARY KEY,
        phone TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        is_admin INTEGER NOT NULL DEFAULT 0,
        blocked INTEGER NOT NULL DEFAULT 0,
        expires_at INTEGER,
        created_at INTEGER NOT NULL,
        last_seen INTEGER,
        login_count INTEGER NOT NULL DEFAULT 0,
        analysis_count INTEGER NOT NULL DEFAULT 0,
        active_seconds INTEGER NOT NULL DEFAULT 0
    );
    CREATE TABLE IF NOT EXISTS sessions (
        token_hash TEXT PRIMARY KEY,
        member_id INTEGER NOT NULL REFERENCES members(id) ON DELETE CASCADE,
        expires_at INTEGER NOT NULL,
        last_seen INTEGER NOT NULL
    );
    CREATE INDEX IF NOT EXISTS sessions_member ON sessions(member_id);
    CREATE TABLE IF NOT EXISTS auth_attempts (attempted_at INTEGER NOT NULL);
    CREATE INDEX IF NOT EXISTS auth_attempts_time ON auth_attempts(attempted_at);
    CREATE TABLE IF NOT EXISTS pending_members (
        member_id INTEGER PRIMARY KEY REFERENCES members(id) ON DELETE CASCADE
    );
    CREATE TABLE IF NOT EXISTS recommendation_archive (
        match_day TEXT NOT NULL,
        fixture_id TEXT NOT NULL,
        home TEXT NOT NULL,
        away TEXT NOT NULL,
        captured_at INTEGER NOT NULL,
        selections TEXT NOT NULL,
        PRIMARY KEY (match_day, fixture_id)
    );
    """
    if isinstance(db, PostgresConnection):
        db.execute("SELECT pg_advisory_xact_lock(61539001)")
        schema = schema.replace("        id INTEGER PRIMARY KEY,",
                                "        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
        schema = schema.replace("member_id INTEGER", "member_id BIGINT")
        schema = schema.replace(" INTEGER", " BIGINT")
        for statement in schema.split(";"):
            if statement.strip():
                db.execute(statement)
    else:
        db.executescript(schema)

    if isinstance(db, PostgresConnection):
        db.execute("ALTER TABLE members ADD COLUMN IF NOT EXISTS display_name TEXT")
    elif not any(row["name"] == "display_name" for row in db.execute("PRAGMA table_info(members)")):
        db.execute("ALTER TABLE members ADD COLUMN display_name TEXT")


def normalize_name(name):
    if name is None:
        return None
    if not isinstance(name, str) or len(name) > 80:
        raise ValueError("İsim en fazla 80 karakter olabilir")
    return name.strip() or None


def create_member(db, phone, password, *, admin=False, days=None, pending=False, display_name=None):
    phone = normalize_phone(phone)
    display_name = normalize_name(display_name)
    if days is not None and not 1 <= int(days) <= 3650:
        raise ValueError("Gün sayısı 1-3650 arasında olmalı")
    now = int(time.time())
    cursor = db.execute(
        """INSERT INTO members(phone,password_hash,is_admin,expires_at,created_at,display_name) VALUES(?,?,?,?,?,?)
        ON CONFLICT(phone) DO NOTHING RETURNING id""",
        (phone, password_hash(password), int(admin), None if admin or days is None else now + int(days)*86400, now, display_name))
    row = cursor.fetchone()
    if row is None:
        db.commit()
        return None
    member_id = row["id"]
    if pending:
        db.execute("INSERT INTO pending_members VALUES (?)", (member_id,))
    db.commit()
    return member_id


def limit_attempts(db):
    now = int(time.time())
    if isinstance(db, PostgresConnection):
        db.execute("SELECT pg_advisory_xact_lock(61539002)")
    else:
        db.execute("BEGIN IMMEDIATE")
    db.execute("DELETE FROM auth_attempts WHERE attempted_at <= ?", (now - 60,))
    count = db.execute("SELECT COUNT(*) AS total FROM auth_attempts").fetchone()["total"]
    if count >= 30:
        db.commit()
        raise OverflowError("Çok fazla deneme. Bir dakika sonra tekrar deneyin.")
    db.execute("INSERT INTO auth_attempts VALUES (?)", (now,))
    db.commit()


def reset_password(db, member_id, password):
    new_hash = password_hash(password)
    db.execute("UPDATE members SET password_hash=? WHERE id=?", (new_hash, member_id))
    db.execute("DELETE FROM sessions WHERE member_id=?", (member_id,))


def login(db, phone, password, display_name=None):
    phone = normalize_phone(phone)
    member = db.execute("SELECT * FROM members WHERE phone=?", (phone,)).fetchone()
    # Equalize nonexistent-account work; do not reveal which phone numbers exist.
    fallback = f"pbkdf2_sha256${ITERATIONS}${'00' * 16}${'00' * 32}"
    password_valid = isinstance(password, str) and len(password) <= 256 and verify_password(
        password, member["password_hash"] if member else fallback
    )
    if not password_valid or member is None:
        raise ValueError("Telefon veya şifre hatalı")
    now = int(time.time())
    if db.execute("SELECT 1 FROM pending_members WHERE member_id=?", (member["id"],)).fetchone():
        raise PermissionError("Hesabınız yönetici onayı bekliyor")
    if member["blocked"] or (not member["is_admin"] and member["expires_at"] is not None and member["expires_at"] <= now):
        raise PermissionError("Üyelik kapalı veya süresi dolmuş")
    updated = db.execute(
        "UPDATE members SET login_count=login_count+1,last_seen=?,display_name=COALESCE(?,display_name) WHERE id=? AND password_hash=?",
        (now, normalize_name(display_name), member["id"], member["password_hash"]),
    )
    if updated.rowcount != 1:
        raise ValueError("Telefon veya şifre hatalı")
    db.execute("DELETE FROM sessions WHERE expires_at <= ?", (now,))
    token = secrets.token_urlsafe(32)
    db.execute("INSERT INTO sessions VALUES(?,?,?,?)",
               (hashlib.sha256(token.encode()).hexdigest(), member["id"], now+SESSION_SECONDS, now))
    db.commit()
    return token


def authenticate(db, token, *, count_analysis=False):
    if not token:
        raise PermissionError("Giriş yapmanız gerekiyor")
    key = hashlib.sha256(token.encode()).hexdigest()
    now = int(time.time())
    row = db.execute("""SELECT m.*,s.last_seen AS session_seen,s.expires_at AS session_expiry
        FROM sessions s JOIN members m ON m.id=s.member_id WHERE s.token_hash=?""", (key,)).fetchone()
    if not row or row["blocked"] or row["session_expiry"] <= now or (
        not row["is_admin"] and row["expires_at"] is not None and row["expires_at"] <= now
    ):
        raise PermissionError("Oturum geçersiz veya üyelik kapalı")
    elapsed = min(max(0, now-row["session_seen"]), 300)
    db.execute("UPDATE sessions SET last_seen=? WHERE token_hash=?", (now,key))
    db.execute("""UPDATE members SET last_seen=?,active_seconds=active_seconds+?,
        analysis_count=analysis_count+? WHERE id=?""",
        (now,elapsed,int(count_analysis),row["id"]))
    db.commit()
    return dict(row)


def set_access(db, member_id, *, blocked=None, days=None):
    member = db.execute("SELECT id FROM members WHERE id=?", (member_id,)).fetchone()
    if not member:
        raise ValueError("Kullanıcı bulunamadı")
    if blocked is not None:
        db.execute("UPDATE members SET blocked=? WHERE id=?", (int(bool(blocked)),member_id))
        if blocked:
            db.execute("DELETE FROM sessions WHERE member_id=?", (member_id,))
    if days is not None:
        is_admin = db.execute("SELECT is_admin FROM members WHERE id=?", (member_id,)).fetchone()["is_admin"]
        if is_admin:
            raise ValueError("Yönetici üyeliğine süre sınırı konulamaz")
        if not 1 <= int(days) <= 3650:
            raise ValueError("Gün sayısı 1-3650 arasında olmalı")
        db.execute("UPDATE members SET expires_at=? WHERE id=?",
                   (int(time.time())+int(days)*86400,member_id))
    db.commit()


def logout(db, token):
    if token:
        db.execute("DELETE FROM sessions WHERE token_hash=?", (hashlib.sha256(token.encode()).hexdigest(),))
        db.commit()


def approve(db, member_id):
    db.execute("DELETE FROM pending_members WHERE member_id=?", (member_id,))
    db.commit()


def members(db):
    return [dict(row) for row in db.execute("""SELECT id,phone,display_name,is_admin,blocked,
        expires_at,created_at,last_seen,login_count,analysis_count,active_seconds,
        EXISTS(SELECT 1 FROM pending_members WHERE member_id=members.id) AS pending
        FROM members ORDER BY id""")]


def online_count(db):
    now = int(time.time())
    return db.execute("""SELECT COUNT(DISTINCT s.member_id) AS total
        FROM sessions s JOIN members m ON m.id=s.member_id
        WHERE s.last_seen > ? AND s.expires_at > ?
          AND m.is_admin=0 AND m.blocked=0
          AND (m.expires_at IS NULL OR m.expires_at > ?)
          AND NOT EXISTS (SELECT 1 FROM pending_members p WHERE p.member_id=m.id)
        """, (now - 120, now, now)).fetchone()["total"]
